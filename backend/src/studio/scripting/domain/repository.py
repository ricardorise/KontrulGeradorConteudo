from typing import Protocol
from uuid import UUID

from studio.scripting.domain.config import ScriptProfile
from studio.scripting.domain.script import BrollSuggestion, Cut, Script


class ScriptRepository(Protocol):
    async def add(self, script: Script) -> None: ...

    async def save(self, script: Script) -> None: ...

    async def get(self, script_id: UUID) -> Script | None: ...

    async def get_latest_for_news_item(self, news_item_id: UUID) -> Script | None: ...

    async def add_broll(self, paragraph_id: UUID, suggestion: BrollSuggestion) -> None: ...

    async def update_broll(self, suggestion: BrollSuggestion) -> None: ...

    async def delete_broll(self, broll_id: UUID) -> None: ...

    async def add_cut(self, script_id: UUID, cut: Cut) -> None: ...

    async def delete_cut(self, cut_id: UUID) -> None: ...

    async def set_cut_excerpt(self, cut: Cut) -> None: ...

    async def fail_interrupted(self) -> int: ...


class ScriptProfileRepository(Protocol):
    """Perfis de roteirista cadastrados pelo editor (os básicos são constantes do domínio)."""

    async def list_custom(self) -> list[ScriptProfile]: ...

    async def get(self, profile_id: str) -> ScriptProfile | None: ...

    async def add(self, profile: ScriptProfile) -> None: ...

    async def delete(self, profile_id: str) -> bool: ...
