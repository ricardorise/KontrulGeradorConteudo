from typing import Protocol
from uuid import UUID

from studio.rendering.domain.asset import AssetKind, RenderAsset
from studio.rendering.domain.render_job import RenderJob


class RenderJobRepository(Protocol):
    async def add(self, job: RenderJob) -> None: ...

    async def save(self, job: RenderJob) -> None: ...

    async def get(self, job_id: UUID) -> RenderJob | None: ...

    async def list_for_script(self, script_id: UUID, limit: int) -> list[RenderJob]: ...

    async def list_active(self) -> list[RenderJob]: ...


class RenderAssetRepository(Protocol):
    async def add(self, asset: RenderAsset) -> None: ...

    async def get(self, asset_id: UUID) -> RenderAsset | None: ...

    async def list(self, kind: AssetKind | None) -> list[RenderAsset]: ...

    async def delete(self, asset_id: UUID) -> None: ...
